#!/usr/bin/env python3
"""Build a real package installation, then exercise its offline APT lifecycle.

Run in the pinned native build container with CAP_SYS_ADMIN and CAP_NET_ADMIN. All test DEBs are
existing Debian archive files. Neither this driver nor its Bazel graph builds a
DEB. Every package transaction gets a separate mount/PID/network namespace.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import tempfile

MACHINES = {"amd64": "x86_64", "arm64": "aarch64"}
NOTICE = "AUTO-GENERATED by e2e/apt_install/validate.py. DO NOT EDIT MANUALLY."


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def audit_graph(document):
    """Reject package-producing actions before executing the selected graph."""
    fragments = {str(row["id"]): row for row in document.get("pathFragments", [])}
    def path(identifier):
        row = fragments[str(identifier)]
        return (path(row["parentId"]) + "/" if row.get("parentId") else "") + row["label"]
    artifacts = {str(row["id"]): path(row["pathFragmentId"]) for row in document.get("artifacts", [])}
    actions = document.get("actions", [])
    require(actions, "Action audit did not find any actions")
    outputs = [artifacts[str(identifier)] for action in actions for identifier in action.get("outputIds", [])]
    require(not any(name.endswith((".deb", ".udeb", ".ddeb")) for name in outputs), "Selected graph would produce a Debian package")
    for action in actions:
        command = " ".join(action.get("arguments", []))
        require(not re.search(r"(?:^|[\s/])dpkg-buildpackage(?:[\s;]|$)", command),
                "Selected graph invokes dpkg-buildpackage")
        require(not re.search(r"(?:^|[\s/])dpkg-deb\b[^;|&\n]*(?:--build\b|(?:^|\s)-[A-Za-z]*b[A-Za-z]*(?:\s|$))", command),
                "Selected graph invokes dpkg-deb package creation")
        require(not re.search(r"(?:^|[\s/])(?:build_deb|package_deb|pkg_deb)(?:\.py|\.sh)?(?:[\s;]|$)", command),
                "Selected graph invokes a Debian packaging wrapper")
    return {"actions": len(actions), "outputs": len(outputs), "debian_package_outputs": 0,
            "debian_package_commands": 0}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--architecture", choices=MACHINES, required=True)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--bazel", default="bazel")
    parser.add_argument("--repository-cache")
    parser.add_argument("--execution-environment", required=True, help="Pinned container reference supplied by the caller")
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    report = {"_generated": NOTICE, "status": "running", "architecture": args.architecture, "commands": []}
    counter = 0

    def run(command, *, check=True):
        nonlocal counter
        counter += 1
        result = subprocess.run(command, text=True, capture_output=True, timeout=1800)
        prefix = "%03d" % counter
        (output / (prefix + ".stdout.log")).write_text(result.stdout)
        (output / (prefix + ".stderr.log")).write_text(result.stderr)
        report["commands"].append({"command": command, "returncode": result.returncode, "log_prefix": prefix})
        require(not check or result.returncode == 0, "Command failed: " + repr(command) + "\n" + result.stderr[-4000:])
        return result.stdout

    try:
        require(platform.machine() == MACHINES[args.architecture] and os.geteuid() == 0,
                "Validation requires a real-root container on the selected native host")
        report["host_machine"] = platform.machine()
        report["revision"] = run(["git", "rev-parse", "HEAD"]).strip()
        report["requested_execution_environment"] = args.execution_environment
        report["verification_tool_versions"] = run(["dpkg-query", "-W", "-f=${Package}\t${Version}\n",
                                                     "gcc", "libarchive-tools", "python3", "git", "ca-certificates"]).splitlines()
        if os.environ.get("GITHUB_RUN_ID"):
            report["ci_run"] = "https://github.com/%s/actions/runs/%s" % (os.environ["GITHUB_REPOSITORY"], os.environ["GITHUB_RUN_ID"])
        bazel = [args.bazel, "--batch", "--output_base=/tmp/apt-install-bazel"]
        options = ["--jobs=2", "--local_resources=cpu=2", "--lockfile_mode=update"]
        if args.repository_cache:
            options.append("--repository_cache=" + args.repository_cache)
        graph = run([*bazel, "aquery", *options, "--output=jsonproto", "//:configured + //:transaction_packages + //:bubblewrap"])
        (output / "action-graph.json").write_text(graph)
        report["action_audit"] = audit_graph(json.loads(graph))
        run([*bazel, "build", *options, "//:configured", "//:configuration_receipt", "//:transaction_packages", "//:bubblewrap"])
        execution_root = Path(run([*bazel, "info", "execution_root"]).strip())
        def artifact(label):
            paths = run([*bazel, "cquery", *options, "--output=files", label]).splitlines()
            require(len(paths) == 1, "Expected one artifact from " + label)
            return execution_root / paths[0]
        archive = artifact("//:configured")
        receipt_path = artifact("//:configuration_receipt")
        bwrap = artifact("//:bubblewrap")
        shutil.copyfile(receipt_path, output / "installation.json")
        report["archive_sha256"] = sha(archive)
        report["installation_receipt_sha256"] = sha(receipt_path)
        installation = json.loads(receipt_path.read_text())
        require(installation.get("status") == "passed" and installation.get("operation") == "apt_install" and
                installation.get("architecture") == args.architecture and installation.get("rootfs_sha256") == sha(archive),
                "Installation receipt does not describe this native root filesystem")
        require(installation.get("requested_execution_environment") == args.execution_environment,
                "The caller's execution environment differs from the rule's declared environment")
        inputs = json.loads(Path("packages.lock.json").read_text())["architectures"][args.architecture]
        base = artifact("@apt_fixture//:base.tar.gz")
        require(sha(base) == inputs["base"]["sha256"] == installation.get("base_sha256"),
                "Installation base differs from the locked input")
        selected = {name: entry for name, entry in inputs["packages"].items() if name != "bubblewrap"}
        actual_inputs = installation.get("input_packages", [])
        require(len(actual_inputs) == len(selected) and
                sorted(entry["sha256"] for entry in actual_inputs) == sorted(entry["sha256"] for entry in selected.values()),
                "Installer receipt differs from the locked package inputs")
        expected_installed = {
            name if entry["architecture"] == "all" else name + ":" + entry["architecture"]:
                {"version": entry["version"], "architecture": entry["architecture"]}
            for name, entry in selected.items()
        }
        require(installation.get("installed_input_packages") == expected_installed,
                "Installed input package versions differ from the lock")
        report["locked_inputs"] = {"base_sha256": sha(base), "package_count": len(selected)}
        run([*bazel, "build", *options, "--build_event_json_file=" + str(output / "cached-build.json"), "//:configured"])
        require(sha(archive) == report["archive_sha256"] and sha(receipt_path) == report["installation_receipt_sha256"],
                "No-op rebuild changed the installation outputs")
        report["unchanged_rebuild"] = {"outputs_unchanged": True}
        with tempfile.TemporaryDirectory(prefix="apt-installed-root-") as temporary:
            root = Path(temporary)
            run(["bsdtar", "-xf", str(archive), "-C", str(root)])
            def guest(*command):
                return run([str(bwrap), "--die-with-parent", "--new-session", "--unshare-pid", "--unshare-net",
                            "--unshare-ipc", "--unshare-uts", "--cap-drop", "ALL", "--cap-add", "CAP_CHOWN",
                            "--cap-add", "CAP_DAC_OVERRIDE", "--cap-add", "CAP_FOWNER", "--cap-add", "CAP_FSETID",
                            "--cap-add", "CAP_SETUID", "--cap-add", "CAP_SETGID", "--cap-add", "CAP_SETFCAP",
                            "--bind", str(root), "/", "--proc", "/proc",
                            "--dev", "/dev", "--tmpfs", "/tmp", "--clearenv", "--setenv", "PATH",
                            "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin", "--setenv", "LC_ALL", "C",
                            "--setenv", "DEBIAN_FRONTEND", "noninteractive", "--chdir", "/", "--", *command])
            def inventory():
                return dict(line.split("\t", 1) for line in guest("dpkg-query", "-W", "-f=${binary:Package}\t${Version}\n").splitlines())
            def audit():
                require(not guest("dpkg", "--audit").strip(), "dpkg reports incomplete installation")
                guest("apt-get", "check")
            require(guest("dpkg", "--print-architecture").strip() == args.architecture, "Wrong installed architecture")
            audit()
            apt_user = guest("getent", "passwd", "_apt").strip().split(":")
            partial_uid = guest("stat", "-c", "%u", "/var/cache/apt/archives/partial").strip()
            require(len(apt_user) == 7 and int(apt_user[2]) > 0 and partial_uid == apt_user[2],
                    "Rootfs archive lost the APT download directory's non-root owner")
            original = inventory()
            require(original == {name: entry["version"] for name, entry in installation["installed_packages"].items()},
                    "Installed package inventory differs from the rule receipt")
            # No configure/update/install command precedes these checks.
            guest("test", "-s", "/etc/ca-certificates.conf")
            guest("test", "-s", "/etc/ssl/certs/ca-certificates.crt")
            hashes = guest("find", "/etc/ssl/certs", "-maxdepth", "1", "-type", "l", "-name", "????????.?").splitlines()
            require(hashes, "CA postinst did not generate certificate hash links")
            guest("test", "-e", hashes[0])
            require("Value: /usr/bin/vim.tiny" in guest("update-alternatives", "--query", "editor"), "Vim was not configured")
            require("Value: /usr/bin/less" in guest("update-alternatives", "--query", "pager"), "Less was not configured")
            require(guest("readlink", "-f", "/usr/bin/editor").strip() == "/usr/bin/vim.tiny", "Editor link differs from alternatives")
            user = guest("getent", "passwd", "uuidd").strip().split(":")
            group = guest("getent", "group", "uuidd").strip().split(":")
            require(len(user) == 7 and len(group) == 4 and int(user[2]) > 0 and user[3] == group[2], "uuidd system account was not configured")
            require("libpcre2-16.so.0" in guest("/sbin/ldconfig", "-p"), "New library was not processed by the ldconfig trigger")
            for line in guest("dpkg-query", "-W", "-f=${binary:Package}\t${Triggers-Pending}\t${Triggers-Awaited}\n").splitlines():
                require(not any(line.split("\t")[1:]), "Unprocessed package trigger: " + line)
            report["initial_configuration"] = {"status": "passed", "certificate_hash_links": len(hashes),
                                                "uuidd_uid": int(user[2]), "uuidd_gid": int(group[2]),
                                                "ldconfig_library": "libpcre2-16.so.0", "apt_partial_uid": int(partial_uid)}
            repository = root / "probe/packages"
            repository.mkdir(parents=True)
            paragraphs = []
            for index, entry in enumerate(inputs["transactions"]):
                source = artifact("@apt_fixture//:hello-%d.deb" % index)
                require(sha(source) == entry["sha256"], "Transaction DEB differs from its lock")
                name = "hello-%d.deb" % index
                shutil.copyfile(source, repository / name)
                control = run(["dpkg-deb", "--field", str(source)]).rstrip()
                paragraphs.append(control + "\nFilename: " + name + "\nSize: " + str(entry["bytes"]) + "\nSHA256: " + entry["sha256"])
            (repository / "Packages").write_text("\n\n".join(paragraphs) + "\n\n")
            (root / "probe/sources.list").write_text("deb [trusted=yes] file:/probe/packages ./\n")
            guest("mkdir", "-p", "/var/lib/apt/lists/apt-install-test/partial")
            def apt(*command):
                return guest("apt-get", "-y", "-o", "Dir::Etc::sourcelist=/probe/sources.list",
                             "-o", "Dir::Etc::sourceparts=-", "-o", "Dir::State::lists=/var/lib/apt/lists/apt-install-test",
                             "-o", "Acquire::Languages=none", "-o", "Dpkg::Use-Pty=0", *command)
            apt("update")
            apt("install", "hello=2.10-3")
            require(inventory().get("hello") == "2.10-3", "APT installed the wrong hello version")
            guest("/usr/bin/hello")
            audit()
            apt("upgrade")
            upgraded = inventory()
            require(upgraded.pop("hello", None) == "2.10-5" and upgraded == original, "APT upgrade changed unexpected packages")
            guest("/usr/bin/hello")
            audit()
            apt("remove", "hello")
            guest("test", "!", "-e", "/usr/bin/hello")
            audit()
            conffiles = [line.split()[0] for line in guest("dpkg-query", "-W", "-f=${Conffiles}", "vim-tiny").splitlines() if line.strip()]
            require(conffiles, "Vim probe has no configuration files")
            apt("remove", "vim-tiny")
            guest("test", "!", "-e", "/usr/bin/vim.tiny")
            guest("test", "!", "-L", "/etc/alternatives/editor")
            for name in conffiles:
                guest("test", "-f", name)
            apt("purge", "vim-tiny")
            for name in conffiles:
                guest("test", "!", "-e", name)
            apt("remove", "less")
            require(guest("readlink", "-f", "/usr/bin/pager").strip() == "/usr/bin/more", "Removing less did not restore more")
            audit()
            report["transactions"] = {"status": "passed", "hello_installed": "2.10-3", "hello_upgraded": "2.10-5",
                                      "hello_removed": True, "vim_configuration_preserved_then_purged": conffiles,
                                      "pager_after_less_removal": "/usr/bin/more"}
        report["status"] = "passed"
    except Exception as error:
        report.update(status="failed", error=str(error))
        raise
    finally:
        if Path("MODULE.bazel.lock").is_file():
            shutil.copyfile("MODULE.bazel.lock", output / "MODULE.bazel.lock")
        (output / "receipt.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
